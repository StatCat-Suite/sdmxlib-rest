"""Render an ``/availability`` response from value lists.

The library's availability route computes two things and then renders them:
per-component distinct value sets, and the observation count under the full
filter. Everything after those two is format work — synthesising the
``DataConstraint``, walking ``references=``, 204-on-empty, XML/JSON negotiation,
the ``obs_count`` annotation .Stat reads, and localisation.

This module is that second half, callable on its own. A consumer that has the
value lists from somewhere other than a live scan — a table its producer baked
into the bundle, its own cache, anything — can get a conformant response without
reimplementing the format.

**This is a helper because the response shape is spec work**, the same for
every catalog; *where the values come from* is a catalog decision. The ``/data``
plane follows the same division: the library owns the helpers and the consumer
owns the orchestration. The alternative — a consumer
caching rendered bytes — makes every (format x language x query spelling) its own
cache entry and leaves two renderers that can drift: baked entries planted
under each accept variant still miss ``?lang=fr``, and baked bodies need
patching wherever they and the live renderer disagree. See #7.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any, TypedDict

import sdmxlib as sl
from fastapi import HTTPException
from fastapi.responses import Response
from sdmxlib.formats import to_json, to_xml
from sdmxlib.model.annotations import Annotation, Annotations
from sdmxlib.model.constraint import (
    ConstraintAttachment,
    ConstraintType,
    CubeRegion,
    DataConstraint,
    KeyValue,
)
from sdmxlib.model.dataflow import Dataflow
from sdmxlib.model.message import StructureMessage
from sdmxlib.model.ref import Ref

from sdmxlib_rest.localization import localized_json_response
from sdmxlib_rest.negotiation import is_browser_request

if TYPE_CHECKING:
    from collections.abc import Sequence

#: The route writes the three-part version sdmxlib's writers emit; the
#: version-advertise middleware rewrites it to the two-part wire form.
JSON_MEDIA = "application/vnd.sdmx.structure+json;version=2.0.0"

_AC_REFERENCES_VALID = frozenset(
    {"none", "all", "datastructure", "dataflow", "codelist", "conceptscheme", "dataproviderscheme", "valuelist"},
)

_AC_REFERENCES_ALL_EXPANSION = ("datastructure", "dataflow", "codelist", "conceptscheme")

#: Both .Stat's mock catalogue and the OECD .NET writer emit this label verbatim.
_AUTOGENERATED_NAME = "Autogenerated content constraint"


def render_availability(
    *,
    registry: sl.LocalRegistry,
    flow_urn: sl.SdmxUrn[Dataflow],
    component_id: str,
    key_values: Sequence[KeyValue],
    obs_count: int,
    accept: str | None,
    accept_language: str | None,
    references: str = "none",
) -> Response:
    """Build the availability response for one flow's value lists.

    Args:
        registry: Needed only for the ``references=`` walk, which resolves
            related artefacts out of the flow's DSD. A caller passing
            ``references="none"`` never reaches it, but it is not optional in
            the signature because the walk cannot be done without it — a
            consumer rendering purely from baked values has to accept that
            ``references=`` is the one part it cannot serve offline.
        flow_urn: The dataflow the constraint attaches to.
        component_id: The ``componentID`` path segment, verbatim — it names the
            constraint (``AVAIL_<component_id>``), so ``all`` and a specific
            dimension produce different artefacts.
        key_values: One entry per enumerated component. Order is preserved into
            the cube region, so a caller reading precomputed lists should keep
            the component order it would have scanned in.
        obs_count: Rows under the FULL filter — every constraint applied, even
            under ``mode=available`` where the per-component lists are wider.
            This is the number .Stat shows in its "(N observations)" badge, so it
            stays tied to the user's actual query rather than to the relaxations.
        accept: Drives XML vs JSON. Browser ``Accept`` headers naming XML are
            treated as wanting JSON.
        accept_language: Localises the JSON body.
        references: ``acreferences`` token list; ``"none"`` adds nothing.

    Returns:
        A 204 when ``obs_count`` is zero — the partial key matched no rows, so
        there is no per-component content to render — and otherwise the
        serialised ``StructureMessage``.
    """
    constraint = DataConstraint(
        id=f"AVAIL_{component_id}",
        maintainer=sl.Agency(id=flow_urn.agency),
        # Every NameableArtefact requires a name — sdmxlib validates on
        # serialise, and an unnamed constraint cannot be written in any of the
        # three formats this emits. Derived rather than configurable: the
        # constraint is synthesised per request, so there is nobody to ask for a
        # better one, and the flow plus component is what identifies it.
        name=sl.InternationalString(en=f"Availability for {flow_urn.id} ({component_id})"),
        version="1.0",
        constraint_type=ConstraintType.ACTUAL,
        attachment=ConstraintAttachment(dataflows=(Ref[Dataflow].unresolved(flow_urn),)),
        regions=(CubeRegion(include=True, keys=tuple(key_values)),),
        annotations=Annotations([Annotation(id="obs_count", title=str(obs_count), type="sdmx_metrics")]),
    )
    # acreferences walk (closes #24): per requested artefact-type token, add the
    # named related artefacts to the StructureMessage alongside the constraint so
    # one response carries everything a client needs to render a value picker
    # (codelists for labels, concept schemes for descriptions, etc.).
    ac = _resolve_acreferences(registry, flow_urn, _parse_acreferences(references))
    msg = StructureMessage(
        constraints=[constraint],
        codelists=ac["codelists"],
        concept_schemes=ac["concept_schemes"],
        data_structures=ac["data_structures"],
        dataflows=ac["dataflows"],
    )

    # 204 No Content when the cube region is empty — the partial key plus filters
    # matched zero rows (closes #32). The constraint envelope still exists
    # conceptually; 204 tells strict clients there is nothing to render.
    if obs_count == 0:
        return Response(status_code=204)

    accept_lower = (accept or "").lower()
    # Browsers send `text/html,application/xhtml+xml,application/xml;…` — they do
    # not actually want SDMX-ML. Detect that and fall through to JSON.
    if "xml" in accept_lower and not is_browser_request(accept):
        sdmx_version = "3.0" if "3.0" in accept_lower else "2.1"
        return Response(
            content=to_xml(msg, version=sdmx_version),
            media_type=f"application/vnd.sdmx.structure+xml;version={sdmx_version}",
        )
    return localized_json_response(
        _inject_constraint_annotations(to_json(msg), obs_count),
        media_type=JSON_MEDIA,
        accept_language=accept_language,
        accept=accept,
    )


def _parse_acreferences(raw: str) -> frozenset[str]:
    """Parse the comma-separated ``references=`` value into a set of artefact-type tokens.

    Returns an empty set when the caller passed ``none`` (or omitted the
    param). Unknown tokens raise 400 — strict spec clients should know
    what they're asking for.
    """
    if not raw:
        return frozenset()
    tokens = {t.strip().lower() for t in raw.split(",") if t.strip()}
    unknown = tokens - _AC_REFERENCES_VALID
    if unknown:
        raise HTTPException(
            status_code=400,
            detail=(f"unknown references token(s): {sorted(unknown)}. Valid values: {sorted(_AC_REFERENCES_VALID)}."),
        )
    if not tokens or tokens == {"none"}:
        return frozenset()
    if "all" in tokens:
        return frozenset(_AC_REFERENCES_ALL_EXPANSION)
    return frozenset(tokens - {"none"})


def _collect_codelist_stubs(registry: sl.LocalRegistry, dsd: sl.DataStructure) -> list[object]:
    """Stubbed codelists for every dim of ``dsd`` — deduped by URN."""
    # Lazy import to break the routes/structure ↔ routes/availability cycle.
    from sdmxlib_rest.routes.structure import _stub_of  # noqa: PLC0415

    out: list[object] = []
    seen: set[str] = set()
    for cl in dsd.all_codelists.values():
        cl_urn = sl.Codelist.urn_for(agency=cl.agency_id, id=cl.id, version=cl.version)
        key = str(cl_urn)
        if key in seen:
            continue
        seen.add(key)
        cl_raw = registry.get(cl_urn)
        if cl_raw is None:
            continue
        out.append(_stub_of(cl_raw))
    return out


def _collect_concept_scheme_stubs(registry: sl.LocalRegistry, dsd: sl.DataStructure) -> list[object]:
    """Stubbed concept schemes referenced by ``dsd``'s components."""
    from sdmxlib_rest.routes.structure import _concept_scheme_urns_for_dsd, _stub_of  # noqa: PLC0415

    out: list[object] = []
    for cs_urn in _concept_scheme_urns_for_dsd(dsd):
        cs_raw = registry.get(cs_urn)
        if cs_raw is None:
            continue
        out.append(_stub_of(cs_raw))
    return out


class _AcReferences(TypedDict):
    """The related-artefact slots `_resolve_acreferences` fills for the ``StructureMessage``."""

    codelists: list[Any]
    concept_schemes: list[Any]
    data_structures: list[Any]
    dataflows: list[Any]


def _resolve_acreferences(
    registry: sl.LocalRegistry,
    flow_urn: sl.SdmxUrn[Dataflow],
    requested: frozenset[str],
) -> _AcReferences:
    """Walk the dataflow's DSD per requested artefact type, filling each related-artefact slot.

    Uses the same lazy/stub helpers as the structure route's reference
    walks. The constraint payload itself is built by the caller; we just
    return the related-artefact slots (codelists, concept_schemes,
    data_structures, dataflows) to splice in.
    """
    from sdmxlib_rest.routes.structure import _stub_of  # noqa: PLC0415

    out: _AcReferences = {
        "codelists": [],
        "concept_schemes": [],
        "data_structures": [],
        "dataflows": [],
    }
    if not requested:
        return out

    dataflow_raw = registry.get(flow_urn)
    if not isinstance(dataflow_raw, sl.Dataflow) or dataflow_raw.structure is None:
        return out
    dsd_raw = registry.get(dataflow_raw.structure.urn)
    materialize = getattr(dsd_raw, "materialize", None) if dsd_raw is not None else None
    dsd = materialize() if callable(materialize) else dsd_raw

    if "dataflow" in requested:
        out["dataflows"].append(_stub_of(dataflow_raw))
    if not isinstance(dsd, sl.DataStructure):
        return out
    if "datastructure" in requested:
        out["data_structures"].append(_stub_of(dsd))
    if "codelist" in requested:
        out["codelists"].extend(_collect_codelist_stubs(registry, dsd))
    if "conceptscheme" in requested:
        out["concept_schemes"].extend(_collect_concept_scheme_stubs(registry, dsd))
    return out


def _inject_constraint_annotations(body: bytes, obs_count: int) -> bytes:
    """Shape the serialised constraint(s) to match the SDMX-JSON 1.0 contract .Stat reads.

    sdmxlib's SDMX-JSON 2.0 writer drops several fields the OECD .NET
    reference writer (JsonV10AvailableConstraintWriter) emits on a
    ContentConstraint:

    - ``annotations[obs_count]`` — DLM / Explorer use this for the row
      count display.
    - ``type: "Actual"`` — required by the SDMX-REST 1.5 spec to
      distinguish the actual-values constraint we synthesise here from
      a codelist-defined Allowed constraint. Without it, strict
      consumers reject the artefact.
    - ``name`` / ``names`` — required label per the spec; .Stat's mock
      catalogue and the OECD writer both emit "Autogenerated content
      constraint" verbatim.

    The fields ride the same JSON parse/write trip as the obs_count
    annotation. Cheap relative to the upstream SELECT DISTINCT pipeline.
    """
    parsed = json.loads(body)
    constraints = (parsed.get("data") or {}).get("dataConstraints") or []
    annotation = {"id": "obs_count", "title": str(obs_count), "type": "sdmx_metrics"}
    label = _AUTOGENERATED_NAME
    for c in constraints:
        c["annotations"] = [annotation]
        c["type"] = "Actual"
        c.setdefault("name", label)
        c.setdefault("names", {"en": label})
    return json.dumps(parsed, separators=(",", ":")).encode("utf-8")


